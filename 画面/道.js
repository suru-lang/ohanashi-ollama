// 画面の道(location.hash)。開いているスレッドは「#会話の番号/スレッドの番号」。
// 「#会話の番号」だけ(前の版のリンク)なら、その会話の一番新しく話したスレッドを開く
(() => {
  // 読めなければ null。スレッドがなければ スレッド は 0
  function 道を読む(hash) {
    const m = /^#?(\d+)(?:\/(\d+))?$/.exec(hash || "");
    if (!m || Number(m[1]) <= 0) return null;
    return { 会話: Number(m[1]), スレッド: m[2] ? Number(m[2]) : 0 };
  }
  function 道を作る(会話, スレッド) {
    return スレッド ? `#${会話}/${スレッド}` : `#${会話}`;
  }
  window.道を読む = 道を読む;
  window.道を作る = 道を作る;
})();
