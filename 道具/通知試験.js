// 画面/通知.js(答えが終わったときの通知の中身とタブの題の印)の試験。node 道具/通知試験.js で動かします。
const fs = require("fs");
const path = require("path");
const window = {};
for (const f of ["書式.js", "通知.js"]) new Function("window", fs.readFileSync(path.join(__dirname, "..", "画面", f), "utf8"))(window);

let 数 = 0, 不合格 = 0;
function 比べる(名, 実際, 期待) {
  数++;
  if (JSON.stringify(実際) !== JSON.stringify(期待)) { 不合格++; console.log(`✗ ${名}: 期待 ${JSON.stringify(期待)}・実際 ${JSON.stringify(実際)}`); }
}

// Markdown の記号を除く
for (const [入, 期待] of [
  ["## 見出し\n\n**太字** と *斜体* と `x` と ~~消し~~", "見出し 太字 と 斜体 と x と 消し"],
  ["- a\n- b\n1. c", "a b c"],
  ["> 引用", "引用"],
  ["[リンク](https://example.com) と ![絵](a.png)", "リンク と 絵"],
  ["前\n```js\nlet x = 1;\n```\n後", "前 (コード) 後"],
  ["前\n```\n閉じていない", "前 (コード)"],
  ["| a | b |\n|---|---|\n| 1 | 2 |", "a b 1 2"],
  ["2 * 3 = 6", "2 * 3 = 6"],
]) 比べる(`平文にする ${JSON.stringify(入)}`, window.平文にする(入), 期待);

// 通知の中身
const 印 = window.道具印;
比べる("答え", window.通知の中身({ 題: "題", 答え: "# できました\n\n**結果**は 42 です。" }), { 題: "題", 本文: "できました 結果は 42 です。", 印: "✅ " });
比べる("途中経過は除く",
  window.通知の中身({ 題: "題", 答え: `動かします\n~~~~console\n$ ls\n~~~~\n${印}run\n終わりました。` }),
  { 題: "題", 本文: "終わりました。", 印: "✅ " });
const 長い = window.通知の中身({ 題: "題", 答え: "あ".repeat(300) });
比べる("長い答えは縮める", [...長い.本文].length, 100);
比べる("長い答えの終わり", 長い.本文.endsWith("…"), true);
比べる("失敗", window.通知の中身({ 題: "題", 答え: "途中まで", 誤り: "Ollama につながりません" }), { 題: "題", 本文: "失敗しました: Ollama につながりません", 印: "⚠️ " });
比べる("止めた", window.通知の中身({ 題: "題", 答え: "途中まで", 止めた: true }), null);
比べる("止めた(誤りあり)", window.通知の中身({ 題: "題", 誤り: "x", 止めた: true }), null);
比べる("何もない", window.通知の中身({ 題: "題", 答え: "" }), null);
比べる("題がない", window.通知の中身({ 答え: "はい" }).題, "おはなし");

// タブの題の印
比べる("印を付ける", window.印を付ける("題 - おはなし", "✅ "), "✅ 題 - おはなし");
比べる("印を付け替える", window.印を付ける("✅ 題 - おはなし", "⚠️ "), "⚠️ 題 - おはなし");
比べる("印を外す", window.印を付ける("⚠️ 題 - おはなし", ""), "題 - おはなし");

console.log(`合格 ${数 - 不合格}・不合格 ${不合格}`);
process.exit(不合格 ? 1 : 0);
